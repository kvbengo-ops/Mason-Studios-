-- =============================================================================
-- assets.kind gains 'composite_ref' — the "character with product" shot
-- projects.product_name — the operator-typed product name
--
-- Per .claude/aug-14/SMN-feature-spec.md §3.2, the entire point of the
-- Product step is one generated image: the character holding/showing the
-- product, so that's "the only product shot we need". Before this
-- migration we stored a character reference and a product reference as two
-- unrelated assets and never combined them — the ad-copy equivalent of a
-- stock photo of a person standing next to a stock photo of a box. This
-- migration adds storage for the actual composite, and for the product
-- name that names it in the compiled brief.
--
-- Why 'composite_ref' extends assets.kind rather than becoming its own
-- table: it IS a reference image in every way the `assets` table already
-- models one — one storage_key, generated by the same fal call
-- (web/lib/fal.ts's generateImage, routed to the /edit endpoint because it
-- takes more than one image_url) that produces character_ref and
-- product_ref, uploaded through the same web/lib/storage.ts path, and
-- selected the same "most recent row of this kind" way character/page.tsx
-- already reads character_ref and product_ref. The only thing that's new
-- is which images it was built from, and that lives in the generation
-- code (web/actions/character.ts), not the schema.
--
-- assets.kind is a plain `text` CHECK, not a native Postgres enum (see
-- 0001_init.sql / types/db.ts's "Hand-maintained enum aliases" section for
-- why: it's our own product vocabulary, not a vendor enum, so a CHECK here
-- is the right layer per 0013_project_direction.sql's reasoning). Adding a
-- value to OUR vocabulary is exactly the deliberate, migration-gated
-- product change that reasoning says a CHECK constraint should catch a
-- typo against — same treatment as every other kind already in the list.
--
-- product_name is a plain nullable text column, not a jsonb blob and not
-- required: per spec §3.2 it's an optional field ("Product Name" text,
-- observed populated but never marked required) that the compiler
-- interpolates into the brief so scenes can refer to the product by name
-- (web/lib/claude.ts) — same treatment as character_desc, which is also
-- free text that flows into the same compiler call.
-- =============================================================================

alter table assets drop constraint if exists assets_kind_check;

alter table assets
  add constraint assets_kind_check
  check (kind in ('character_ref', 'product_ref', 'composite_ref', 'ref_frame', 'clip', 'final'));

comment on constraint assets_kind_check on assets is
  'Our own product vocabulary, not a vendor enum — see 0017_composite_asset.sql for why a CHECK '
  'here is the right layer (same reasoning as 0013_project_direction.sql''s shooting_mode/ugc_style). '
  'composite_ref added in 0017: the generated "character with product" image (spec §3.2).';

alter table projects
  add column if not exists product_name text;

comment on column projects.product_name is
  'Operator-typed product name (spec §3.2, e.g. "NeuroBlast SMN16-18"). Optional. Interpolated into '
  'the compiled brief (web/lib/claude.ts) so scenes can refer to the product by name, same treatment '
  'as projects.character_desc.';
